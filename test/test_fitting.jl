# As in test_spectral_data.jl, anything touching the ~123 MB gitignored data file is
# guarded on isfile. Statistics is not a declared dependency, so the one summary
# statistic these tests need is spelled out.
et_file = joinpath(@__DIR__, "..", "data", "sims", "friction", "ErpenbeckThoss",
                   "Lambda_spectrum_Gamma_eV=0.1_Nx=257_T_K=300.0_domega_eV=0.001.h5")

function median_(v)
    s = sort(vec(collect(v)))
    n = length(s)
    return isodd(n) ? s[(n + 1) ÷ 2] : (s[n ÷ 2] + s[n ÷ 2 + 1]) / 2
end

model_values(ps, m, ω) =
    [spectral_density(w, ps, amplitudes(m, i)...) for w in ω, i in 1:n_configurations(m)]

amplitude_matrix(m) =
    reduce(hcat, [vcat(amplitudes(m, i)...) for i in 1:n_configurations(m)])

@testset "Fitting" begin
    # Well-separated poles, so the design matrix is well conditioned and the amplitudes
    # themselves — not merely the fit — are identifiable.
    ps = PoleSet([0.05], [0.02, 0.4], [0.1, 1.5])
    ω = exp.(range(log(1e-3), log(20.0); length = 120))
    truth = GridAmplitudes([0.3, 0.05, 0.0],           # a₀, including an exact zero
                           [1.2 0.4 2.0],              # K_R = 1
                           [0.7 1.1 0.2; 0.05 0.9 1.3])  # K_C = 2
    Y = model_values(ps, truth, ω)

    @testset "fit_column" begin
        M = design_matrix(ps, ω)
        σ = residual_scales(Y)
        θ = fit_column(M, view(Y, :, 1), view(σ, :, 1))

        @test length(θ) == 1 + 1 + 2
        @test all(≥(0), θ)                              # FDT / Bochner, by construction
        # Consistent data with an identifiable design: NNLS recovers the generator.
        @test θ ≈ vcat(amplitudes(truth, 1)...) rtol = 1e-8

        # THE OPTIMALITY CERTIFICATE, independent of what the solver claims. At a KKT
        # point of min‖Aθ - b‖² s.t. θ ≥ 0 the gradient AᵀA θ - Aᵀb must vanish on the
        # active set and be non-negative off it. This checks the answer, not the
        # algorithm, so it survives any change of `alg`.
        A = M ./ view(σ, :, 3)
        b = view(Y, :, 3) ./ view(σ, :, 3)
        θ3 = fit_column(M, view(Y, :, 3), view(σ, :, 3))
        g = permutedims(A) * (A * θ3 .- b)
        scale = maximum(abs, permutedims(A) * b)
        for k in eachindex(θ3)
            if θ3[k] > 0
                @test abs(g[k]) < 1e-8 * scale          # interior ⇒ stationary
            else
                @test g[k] > -1e-8 * scale              # boundary ⇒ pushing outward
            end
        end

        @test_throws DimensionMismatch fit_column(M, Y[1:5, 1], σ[1:5, 1])
        @test_throws DimensionMismatch fit_column(M, view(Y, :, 1), σ[1:5, 1])
        # A weight without a row to weight is a silent no-op waiting to happen.
        @test_throws ArgumentError fit_column(M, view(Y, :, 1), view(σ, :, 1);
                                              anchor_weight = 10)
        @test_throws DimensionMismatch fit_column(M, view(Y, :, 1), view(σ, :, 1);
                                                  anchor = ([1.0, 2.0], 1.0),
                                                  anchor_weight = 10)
    end

    @testset "fit_amplitudes" begin
        m = fit_amplitudes(ps, ω, Y)
        @test m isa GridAmplitudes
        @test n_configurations(m) == 3
        @test mode_counts(m) == (1, 2)
        @test all(≥(0), amplitude_matrix(m))

        # THE LOAD-BEARING TEST. Data generated by the model is recovered by the fit to
        # machine precision — the fit is exact, and on an identifiable design so are the
        # amplitudes. If this fails, nothing downstream means anything.
        @test amplitude_matrix(m) ≈ amplitude_matrix(truth) rtol = 1e-8
        @test maximum(abs, relative_errors(ps, m, ω, Y)) < 1e-10
        # An exactly-zero amplitude is recovered as exactly zero, not as noise: the
        # constraint is active, which is the whole point of using NNLS over least squares.
        @test m.a₀[3] == 0

        # Column i depends only on column i — no coupling until μ is switched on.
        @test fit_column(design_matrix(ps, ω), view(Y, :, 2),
                         view(residual_scales(Y), :, 2)) ≈ amplitude_matrix(m)[:, 2]

        # ε reaches the fit, not just any later scoring: a floor coarse enough to swamp
        # the data changes the answer.
        @test amplitude_matrix(fit_amplitudes(ps, ω, Y; ε = 0.5)) !=
              amplitude_matrix(fit_amplitudes(ps, ω, Y; ε = 1e-8))

        @test_throws DimensionMismatch fit_amplitudes(ps, ω[1:10], Y)
    end

    @testset "the Markovian anchor row" begin
        # On data the model can represent exactly, the anchor is already satisfied and
        # weighting it changes nothing — the anchor adds information, never bias.
        # The tolerances are looser than the unweighted fit's 1e-8 on purpose. A heavy
        # anchor row dominates the normal equations and costs conditioning in every
        # other direction: measured max relative error in the recovered amplitudes runs
        # 2e-15 at w = 0, 2.5e-5 at w = 1, 9e-4 at w = 10, and then *saturates* at
        # 1.4e-3 for w ≳ 100. It plateaus rather than diverging, so a large weight is
        # safe — it simply stops buying anything past the point of equality.
        m_w = fit_amplitudes(ps, ω, Y; anchor_weight = 1e3)
        @test amplitude_matrix(m_w) ≈ amplitude_matrix(truth) rtol = 1e-2
        @test amplitude_matrix(fit_amplitudes(ps, ω, Y; anchor_weight = 1)) ≈
              amplitude_matrix(truth) rtol = 1e-4

        # On data the model *cannot* represent, it bites. A pure ω⁻³ tail is outside the
        # ω⁻² reach of any Lorentzian sum (§3), which is exactly the situation §4's
        # anchor is for.
        hard = [1 / (1 + w)^3 for w in ω, _ in 1:1]
        c = markovian_anchor_row(ps)
        err(mm) = abs(sum(c .* vcat(amplitudes(mm, 1)...)) - hard[1, 1]) / hard[1, 1]
        e0 = err(fit_amplitudes(ps, ω, hard))
        e3 = err(fit_amplitudes(ps, ω, hard; anchor_weight = 1e3))
        @test e3 < e0
        @test e3 < 1e-3                                 # driven essentially to equality
    end

    @testset "a broad zero-centred peak needs real poles" begin
        # The regression that matters most on this data. At the Fermi crossing the
        # resonance collapses onto ω = 0 with half-width Δ + k_BT, and that column
        # carries the global maximum of the dataset. A pair ladder with α tied to β
        # cannot make that shape: as β → 0 the width goes to zero with it, giving a
        # narrow spike rather than a broad zero-centred Lorentzian.
        ωz = exp.(range(log(1e-5), log(5.0); length = 200))
        halfwidth = 0.077 / 27.211386245988          # Δ + k_BT at Γ = 0.1, in Ha
        target = reshape([lorentzian(w, halfwidth) for w in ωz], :, 1)

        pairs_only = log_ladder(1.8e-3, 0.345, 20)
        with_reals = log_ladder(1.8e-3, 0.345, 20; K_R = 12, λ_min = 1.8e-4)

        err(ps) = median_(abs.(relative_errors(ps, fit_amplitudes(ps, ωz, target), ωz, target)))
        @test err(pairs_only) > 0.1                  # pairs alone cannot reach it
        # Not machine precision: the log-spaced rates land near the target width rather
        # than on it (the nearest rung here is 2.81e-3 Ha against a target of 2.83e-3),
        # so the shape is reconstructed from neighbours. 0.004% is the residue of that.
        @test err(with_reals) < 1e-4
        @test err(with_reals) < err(pairs_only) / 1000
    end

    @testset "relative_errors" begin
        m = fit_amplitudes(ps, ω, Y)
        E = relative_errors(ps, m, ω, Y)
        @test size(E) == (length(ω), 3)
        # Longhand, against Part 1's forward map rather than the design matrix.
        R = model_values(ps, m, ω)
        @test E ≈ (R .- Y) ./ abs.(Y)
        # Signed, and relative: a uniform 1% overshoot reads as +0.01 everywhere.
        over = GridAmplitudes(1.01 .* truth.a₀, 1.01 .* truth.a, 1.01 .* truth.A)
        @test relative_errors(ps, over, ω, Y) ≈ fill(0.01, length(ω), 3) rtol = 1e-8
        @test_throws DimensionMismatch relative_errors(ps, m, ω[1:5], Y)
    end

    if isfile(et_file)
        @testset "stage 1 on the Γ = 0.1 spectrum" begin
            s = load_lambda_spectrum(et_file)
            idx = subsample_omega(s.ω)
            ω_r = s.ω[idx]
            Y_r = s.Λ[idx, :]
            ladder = log_ladder(1.8e-3, 0.345, 30)
            low = hartree_to_eV.(ω_r) .<= 1.0
            c = markovian_anchor_row(ladder)
            anchor_err(m) = [abs(sum(c .* vcat(amplitudes(m, i)...)) - Y_r[1, i]) / Y_r[1, i]
                             for i in axes(Y_r, 2)]

            m = fit_amplitudes(ladder, ω_r, Y_r)
            @test n_configurations(m) == 254
            @test mode_counts(m) == (0, 30)
            @test all(≥(0), amplitude_matrix(m))
            # The convenience method assembles the same band and scales.
            @test amplitude_matrix(fit_amplitudes(ladder, s)) == amplitude_matrix(m)

            E = abs.(relative_errors(ladder, m, ω_r, Y_r))

            # The fit is genuinely partial, and these numbers are the record of that.
            # Below 1 eV — where the resonance lives — the median relative error is ~7.5%,
            # against the 0.1–5% §5 leads one to expect from a full-dictionary NNLS.
            @test median_(E[low, :]) ≈ 0.075 rtol = 0.05

            # The far tail is where it goes wrong, and it is not a defect of the fit:
            # Λ decays as ω⁻³ there and no Lorentzian sum can follow it past ω⁻². The
            # σ floor of §3 exists precisely to stop this region from taking over, which
            # is why `objective_value` still lands far below the zero model.
            hi = hartree_to_eV.(ω_r) .> 10.0
            @test median_(E[hi, :]) > 1.0
            v = trapezoid_weights(s.x)
            σ = residual_scales(Y_r)
            J = objective_value(ladder, m, ω_r, Y_r, v, σ)
            J₀ = objective_value(ladder, GridAmplitudes(254, 0, 30), ω_r, Y_r, v, σ)
            @test J / J₀ ≈ 0.189 rtol = 0.02
            @test J < J₀

            # NNLS returns a genuinely sparse answer: about 12 of the 31 atoms are used
            # per column, so 30 rungs is not obviously too few — adding more is not what
            # the fit is short of.
            @test 8 ≤ median_(sum(amplitude_matrix(m) .> 0; dims = 1)) ≤ 16

            # §4's anchor, measured. Unweighted it is just one residual in 561 and comes
            # out ~8% off, up to 88% at the worst column. Weighting it drives it to
            # equality *and improves the rest of the low-ω fit at the same time*, so it
            # buys accuracy rather than trading for it — which is the case for §4's
            # "recommended equality" being taken up.
            a0 = anchor_err(m)
            @test median_(a0) ≈ 0.084 rtol = 0.05
            @test maximum(a0) > 0.5

            m_w = fit_amplitudes(ladder, ω_r, Y_r; anchor_weight = 1e3)
            aw = anchor_err(m_w)
            @test median_(aw) < 1e-3
            @test maximum(aw) < 0.01
            @test median_(abs.(relative_errors(ladder, m_w, ω_r, Y_r))[low, :]) <
                  median_(E[low, :])
        end
    else
        @info "Skipping Fitting tests on real data: $(et_file) not found " *
              "(data/ is gitignored; each file is ~123 MB)."
    end
end
